//! Wire identifiers from the pinned ath11k WMI TLV ABI.
//!
//! Names and values intentionally match `enum wmi_cmd_group`,
//! `enum wmi_tlv_cmd_id`, `enum wmi_tlv_event_id`, `enum wmi_tlv_tag`, and
//! `enum wmi_tlv_service` in Linux `ath11k/wmi.h`. Aliases are constants
//! rather than Rust enum variants because the C ABI assigns duplicate values.

use crate::{CommandId, EventId};

pub const fn command_id(value: u32) -> CommandId {
    CommandId(value)
}
pub const fn event_id(value: u32) -> EventId {
    EventId(value)
}

#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct TlvTag(pub u16);

#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct ServiceId(pub u16);

